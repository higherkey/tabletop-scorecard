import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LUCIDE_DIR = join(ROOT, 'node_modules', 'lucide-static');
const ICON_DIR = join(LUCIDE_DIR, 'icons');
const ICONS_OUT = join(ROOT, 'js', 'icons-data.js');

// Contract name -> current Lucide file name. Used only when the contract name is missing from lucide-static.
const RENAMED_FALLBACKS = {
  'bar-chart-3': 'chart-column',
};

const ICON_NAMES = [
  'dice-5', 'bar-chart-3', 'settings', 'user-round', 'crown', 'share-2', 'flag', 'undo-2', 'plus', 'trash-2',
  'x', 'cloud', 'cloud-off', 'check', 'rotate-ccw', 'download', 'chevron-right', 'users', 'trophy', 'log-out',
  'link-2-off', 'copy',
];

const ELEMENT_RE = /<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/?>/g;
const ATTR_RE = /([\w:-]+)\s*=\s*"([^"]*)"/g;

async function readIconSvg(name) {
  const candidates = [name, RENAMED_FALLBACKS[name]].filter(Boolean);
  for (const candidate of candidates) {
    const file = join(ICON_DIR, `${candidate}.svg`);
    try {
      return { name: candidate, file, svg: await readFile(file, 'utf8') };
    } catch (err) {
      if (err.code !== 'ENOENT') throw err;
    }
  }
  throw new Error(`Lucide icon not found for "${name}"`);
}

function parseElements(svg) {
  const elements = [];
  for (const [, tag, attrSource] of svg.matchAll(ELEMENT_RE)) {
    const attrs = {};
    for (const [, key, value] of attrSource.matchAll(ATTR_RE)) attrs[key] = value;
    elements.push([tag, attrs]);
  }
  return elements;
}

async function writeIcons() {
  const pkg = JSON.parse(await readFile(join(LUCIDE_DIR, 'package.json'), 'utf8'));
  const licenseText = await readFile(join(LUCIDE_DIR, 'LICENSE'), 'utf8');
  const header = [
    '// Generated by scripts/vendor.mjs. Do not edit by hand.',
    `// Icons: Lucide v${pkg.version} (https://lucide.dev), ISC License.`,
    ...licenseText.trimEnd().split('\n').map((line) => (line ? `// ${line}` : '//')),
    '',
  ];

  const entries = [];
  for (const name of ICON_NAMES) {
    const { name: fileName, file, svg } = await readIconSvg(name);
    const elements = parseElements(svg);
    if (elements.length === 0) throw new Error(`No drawable elements parsed from ${file}`);
    const lines = elements.map(([tag, attrs]) => `    [${JSON.stringify(tag)}, ${JSON.stringify(attrs)}],`);
    entries.push(`  ${JSON.stringify(name)}: [\n${lines.join('\n')}\n  ],`);
    const substitution = fileName === name ? '' : ` (substituted: ${name} -> ${fileName})`;
    console.log(`icons: ${name} <- ${relative(ROOT, file)} [${elements.length} elements]${substitution}`);
  }

  const output = `${header.join('\n')}\nexport default {\n${entries.join('\n')}\n};\n`;
  await writeFile(ICONS_OUT, output, 'utf8');
  console.log(`wrote ${relative(ROOT, ICONS_OUT)} (${ICON_NAMES.length} icons)`);
}

async function main() {
  await writeIcons();
}

main().catch((err) => {
  console.error(err.message);
  process.exitCode = 1;
});
